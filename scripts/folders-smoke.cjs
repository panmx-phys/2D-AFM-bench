/* Use a disposable catalog. Generates only synthetic Park TIFF fixtures.
   AFM_PYTHON=.venv/bin/python node scripts/folders-smoke.cjs URL [browser-executable] */
const {chromium}=require(process.env.AFM_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const output=path.resolve('.test-artifacts');
const fixture=fs.mkdtempSync(path.join(output,'folders-fixture-'));
const source=path.join(fixture,'Session');
const moved=path.join(fixture,'Moved session');
fs.mkdirSync(source);
function writeFixture(filename,value=1){execFileSync(process.env.AFM_PYTHON||'python',['-c',
  "import sys;sys.path.insert(0,'tests');from test_importers import park_fixture;import numpy as np;from pathlib import Path;Path(sys.argv[1]).write_bytes(park_fixture(np.arange(48).reshape(6,8)*float(sys.argv[2]),gain=1,scale=2,offset=3,unit='nm'))",path.join(source,filename),String(value)]);}
for(let n=1;n<=3;n++)writeFixture(`00${n}__Z Height_Forward.tiff`);
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.argv[3]?{executablePath:process.argv[3]}:{})});
 try{
 const page=await browser.newPage({viewport:{width:1100,height:800}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>localStorage.setItem('afm-auto-prepare','false'));
 const call=(method,payload={})=>page.evaluate(async({method,payload})=>{const r=await fetch('/api/'+method,{method:'POST',headers:{'Content-Type':'application/json','X-AFM-Token':document.querySelector('meta[name=afm-token]').content},body:JSON.stringify(payload)});const v=await r.json();if(!r.ok)throw Error(JSON.stringify(v));return v;},{method,payload});
 await page.goto(process.argv[2]||'http://127.0.0.1:8772');
 await page.waitForSelector('.session-heading');
 await page.locator('.top-actions [data-action=import]').click();
 await page.locator('#folder-path').fill(source);
 await page.locator('[data-action=import-confirm]').click();
 await page.getByText('Import complete',{exact:true}).waitFor();
 assert.equal(await page.locator('.loading-overlay').count(),0);
 let job=await call('import_status');assert.equal(job.added,3);
 const id=job.session_id;
 await page.locator('[data-action=import-open]').click();
 await page.waitForFunction(id=>state.session?.id===id&&!state.loading,id);
 await page.waitForSelector('.acquisition-card');
 assert.equal(await page.locator('.acquisition-card').count(),3);
 await page.locator('[data-action=dismiss-import]').click();
 await page.locator('[data-action=folders]').click();
 const row=()=>page.locator(`[data-folder-id="${id}"]`);
 await row().locator('[data-action=manage-folder]').click();
 await page.locator('#managed-name').fill('Updated folder test');
 await page.locator('#managed-notes').fill('Retain notes and every source version.');
 await page.locator('[data-action=save-folder]').click();
 await row().getByRole('button',{name:'Updated folder test',exact:true}).waitFor();
 writeFixture('004__Z Height_Forward.tiff');
 await row().locator('[data-action=update-folder]').click();
 await page.getByText('Import complete',{exact:true}).waitFor();
 job=await call('import_status');assert.deepEqual([job.added,job.skipped],[1,3]);
 let session=await call('session',{id});assert.equal(session.scan_count,4);
 const oldScan=session.scans.find(s=>s.filename==='001__Z Height_Forward.tiff');
 await call('process',{id:oldScan.id,operations:[{type:'plane'}]});
 writeFixture('001__Z Height_Forward.tiff',2);
 await page.locator('[data-action=dismiss-import]').click();
 await row().locator('[data-action=update-folder]').click();
 await page.getByText('Import complete',{exact:true}).waitFor();
 session=await call('session',{id});assert.equal(session.scan_count,5);
 assert.deepEqual((await call('scan',{id:oldScan.id})).operations,[{type:'plane'}]);
 await page.locator('[data-action=dismiss-import]').click();
 fs.writeFileSync(path.join(source,'bad.tiff'),'Invalid synthetic fixture');
 await row().locator('[data-action=update-folder]').click();
 await page.getByText('Import complete',{exact:true}).waitFor();
 await page.locator('[data-action=import-errors]').click();
 await page.getByRole('dialog',{name:'Import errors'}).waitFor();
 assert.match(await page.locator('.modal').innerText(),/bad.tiff/);
 await page.locator('[data-action=close-modal]').click();
 await page.locator('[data-action=dismiss-import]').click();
 fs.renameSync(source,moved);
 await row().locator('[data-action=update-folder]').click();
 await page.getByText('Import failed',{exact:true}).waitFor();
 assert.match(await page.locator('#import-progress').innerText(),/unavailable/);
 await page.locator('[data-action=dismiss-import]').click();
 await row().locator('[data-action=manage-folder]').click();
 await page.locator('[data-action=reconnect-folder]').click();
 await page.locator('#reconnect-path').fill(moved);
 await page.locator('[data-action=reconnect-confirm]').click();
 await page.getByText('Import complete',{exact:true}).waitFor();
 session=await call('session',{id});assert.equal(session.source_path,moved);assert.equal(session.scan_count,5);
 assert.equal(session.source_history[0].path,source);
 await page.locator('[data-action=dismiss-import]').click();
 await row().locator('[data-action=manage-folder]').click();
 await page.locator('[data-action=archive-folder]').click();
 await row().waitFor({state:'hidden'});
 assert(!(await call('bootstrap')).sessions.some(s=>s.id===id));
 await page.locator('[data-action=folder-filter][data-value=archived]').click();
 await row().waitFor();
 await row().locator('[data-action=restore-folder]').click();
 await row().waitFor({state:'hidden'});
 await page.locator('[data-action=folder-filter][data-value=active]').click();
 await row().waitFor();
 await page.locator('#global-search').fill(moved);
 await page.waitForFunction(()=>document.querySelectorAll('.folder-row').length===1);
 await page.screenshot({path:path.join(output,'folders-management.png')});
 const minimum=await browser.newPage({viewport:{width:900,height:650}});
 await minimum.goto(process.argv[2]||'http://127.0.0.1:8772');
 await minimum.waitForSelector('.session-heading');
 await minimum.locator('[data-action=folders]').click();
 await minimum.locator('.folder-row').first().waitFor();
 await minimum.locator('#global-search').fill(moved);
 await minimum.waitForFunction(()=>document.querySelectorAll('.folder-row').length===1);
 await minimum.screenshot({path:path.join(output,'folders-minimum.png')});
 assert.equal(await minimum.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await minimum.close();
 await page.reload();
 await page.waitForSelector('.session-heading');
 await page.locator('[data-action=folders]').click();
 assert.match(await row().innerText(),/Updated folder test/);
 assert.equal((await call('session',{id})).notes,'Retain notes and every source version.');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,checks:['import','update','unchanged files','changed source versions','recipe preserved','error details','offline source failure','reconnect and path history','rename and notes','archive and restore','persistence','minimum layout'],session_id:id},null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
