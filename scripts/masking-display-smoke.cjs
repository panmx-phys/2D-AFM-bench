/* Synthetic-only browser validation for editable masks and display ranges.
   AFM_PLAYWRIGHT_MODULE=/path/to/playwright node scripts/masking-display-smoke.cjs URL [browser executable]
   Run against a disposable --browser --data-dir workspace. */
const {chromium}=require(process.env.AFM_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

(async()=>{
  let browser;
  try{
    browser=await chromium.launch({headless:true,...(process.argv[3]?{executablePath:process.argv[3]}:{})});
    const page=await browser.newPage({viewport:{width:1280,height:900},deviceScaleFactor:1});
    await page.addInitScript(() => localStorage.setItem('afm-auto-prepare', 'false')); // Exercise explicit corrections; automatic preparation has its own smoke test.
    const errors=[];let expectedApiFailure=false;
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',message=>{if(message.type()==='error'&&!expectedApiFailure)errors.push(message.text());});
    await page.goto(process.argv[2]||'http://127.0.0.1:8777');
    await page.waitForSelector('.session-heading,.empty-state');
    const session=await page.evaluate(async()=>{const demo=await api('demo');await openSession(demo.id);return demo;});
    assert.equal(session.synthetic,true,'only a synthetic catalog session is changed');
    const scan=session.scans.find(item=>item.channel==='Z Height'&&item.direction==='Forward');
    assert(scan,'synthetic height image exists');
    await page.evaluate(async id=>{
      await api('process',{id,operations:[]});await api('edit_mask',{id,action:'clear'});
      await api('update_mask',{id,masking:'exclude',visible:true});
      await api('set_display',{id,settings:{palette:'amber',mode:'full',clip_percent:0}});
      await openScan(id);
    },scan.id);
    const original=await page.evaluate(async()=>({raw:await api('scan',{id:state.scan.id,raw:true}),saved:await api('scan',{id:state.scan.id})}));
    const idle=async()=>{await page.waitForFunction(()=>!state.loading);await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)));};
    const draw=async(start,end)=>{
      const box=await page.locator('#draw-overlay').boundingBox();assert(box,'image drawing surface exists');
      await page.mouse.move(box.x+box.width*start[0],box.y+box.height*start[1]);await page.mouse.down();
      await page.mouse.move(box.x+box.width*end[0],box.y+box.height*end[1],{steps:12});await page.mouse.up();
    };
    const mask=()=>page.evaluate(()=>state.scan.mask);
    const waitMask=revision=>page.waitForFunction(old=>!state.loading&&state.scan.mask.revision!==old,revision);
    const maskAction=async name=>{const before=await mask();await page.getByRole('button',{name,exact:true}).click();await waitMask(before.revision);return mask();};
    const selectTool=tool=>page.locator(`.canvas-toolbar [data-action="tool"][data-tool="${tool}"]`).click();
    const selectMask=()=>selectTool('mask');
    const showPanel=tab=>page.locator(`[role="tab"][data-action="inspector-tab"][data-tab="${tab}"]`).click();
    const displayAction=action=>page.locator(`#display-controls [data-display-action="${action}"]`).click();
    const fill=async(id,value)=>{await page.locator('#'+id).fill(String(value));await page.locator('#'+id).blur();};

    console.log('Checking rectangle/brush masks and mask history');
    await selectMask();
    await page.locator('[data-mask-shape="rectangle"]').click();
    let before=await mask();await draw([.2,.2],[.55,.55]);await waitMask(before.revision);
    const rectangle=await mask();
    assert(rectangle.count>0&&rectangle.count<scan.width*scan.height,'rectangle selects a proper subset of source pixels');
    assert.equal(rectangle.width,scan.width);assert.equal(rectangle.height,scan.height);
    assert.equal(rectangle.masking,'exclude');
    assert.equal(await page.evaluate(()=>state.scan.masked_statistics.count),scan.width*scan.height-rectangle.count,'surface statistics exclude the marked source pixels');
    await page.locator('[data-mask-shape="brush"]').click();
    await page.locator('[data-mask-edit="erase"]').click();await fill('mask-radius',10);
    before=await mask();await draw([.3,.3],[.45,.45]);await waitMask(before.revision);
    const erased=await mask();assert(erased.count<rectangle.count,'brush erases source pixels');
    let restored=await maskAction('Undo mask');assert.equal(restored.data_base64,rectangle.data_base64,'mask undo restores exact bits');
    restored=await maskAction('Redo mask');assert.equal(restored.data_base64,erased.data_base64,'mask redo restores exact bits');
    const inverted=await maskAction('Invert mask');assert.equal(inverted.count,scan.width*scan.height-erased.count);
    await maskAction('Undo mask');
    await page.locator('#mask-visible').uncheck();await idle();
    assert.equal((await page.evaluate(async()=>api('scan',{id:state.scan.id}))).mask.visible,false,'mask visibility persists');
    await page.locator('#mask-visible').check();await idle();

    console.log('Checking include/exclude measurement and immutable processing snapshots');
    await page.locator('#mask-use').selectOption('include');await idle();
    assert.equal(await page.evaluate(()=>state.scan.masked_statistics.count),erased.count,'include mode measures marked pixels');
    await page.locator('#mask-use').selectOption('exclude');await idle();
    const details=page.locator('#more-corrections');if(!await details.evaluate(el=>el.open))await details.locator('summary').click();
    await page.locator('[data-action="operation"][data-operation="plane"]').click();
    await page.getByRole('button',{name:'Keep result',exact:true}).waitFor();await idle();
    const preview=await page.evaluate(()=>({op:state.pending.at(-1),history:state.scan.history.at(-1)}));
    assert.equal(preview.op.masking,'exclude');assert(Array.isArray(preview.op.mask),'preview contains materialized binary mask');
    assert.equal(preview.history.reference.valid_pixel_count,scan.width*scan.height-erased.count);
    await page.getByRole('button',{name:'Keep result',exact:true}).click();await idle();
    const recipe=await page.evaluate(()=>JSON.stringify(state.scan.operations));
    await selectMask();await maskAction('Clear mask');
    assert.equal(await page.evaluate(()=>JSON.stringify(state.scan.operations)),recipe,'editing the current mask never changes saved recipe snapshots');
    assert.equal((await mask()).count,0);
    await maskAction('Undo mask');assert.equal((await mask()).data_base64,erased.data_base64);
    await page.reload();await page.waitForSelector('.scan-card');await page.evaluate(id=>openScan(id),scan.id);
    assert.equal((await mask()).data_base64,erased.data_base64,'mask survives reload');
    assert.equal(await page.evaluate(()=>JSON.stringify(state.scan.operations)),recipe,'recipe survives reload');
    assert.deepEqual(await page.evaluate(async()=> (await api('scan',{id:state.scan.id,raw:true})).data),original.raw.data,'mask editing leaves original data unchanged');

    console.log('Checking masked profile/area analysis');
    await selectTool('profile');await draw([.05,.4],[.95,.4]);
    await page.waitForFunction(()=>!state.loading&&!!state.profile);
    assert.equal(await page.evaluate(()=>state.profile.masking),'exclude');
    assert(await page.evaluate(()=>state.profile.values.some(value=>value===null)),'profile preserves distances at excluded samples');
    await selectTool('area');await draw([.05,.05],[.95,.95]);
    await page.waitForFunction(()=>!state.loading&&!!state.area);
    assert.equal(await page.evaluate(()=>state.area.masking),'exclude');
    assert(await page.evaluate(()=>state.area.statistics.count<state.scan.width*state.scan.height*.81),'area intersects its rectangle and mask');

    await selectTool('step');await draw([.1,.2],[.35,.5]);await idle();
    await draw([.6,.2],[.9,.5]);await page.waitForFunction(()=>!state.loading&&!!state.step);
    assert(await page.evaluate(()=>state.step.region_a.count<state.scan.width*state.scan.height*.25*.3),'step reference A excludes marked pixels');
    assert(await page.evaluate(()=>state.step.region_b.count>state.step.region_a.count),'step reference B retains its unmasked pixels');

    console.log('Checking manual display limits, persistence and numerical invariance');
    await showPanel('view');
    const beforeDisplay=await page.evaluate(async()=>({scan:await api('scan',{id:state.scan.id}),profile:await api('profile',{id:state.scan.id,start:[.1,.1],end:[.9,.9]})}));
    const [minimum,maximum]=[beforeDisplay.scan.statistics.min,beforeDisplay.scan.statistics.max];
    const manual=[minimum+(maximum-minimum)*.2,maximum-(maximum-minimum)*.2];
    await page.locator('#color-min-input').fill(String(manual[0]));
    await page.locator('#color-max-input').fill(String(manual[1]));
    await displayAction('manual');
    await page.evaluate(()=>AFMDisplay.pending());
    await page.waitForFunction(range=>canvasRanges[0]===range[0]&&canvasRanges[1]===range[1],manual);
    await page.locator('#palette').selectOption('gray');
    await page.evaluate(()=>AFMDisplay.pending());
    await page.waitForFunction(()=>state.palette==='gray');
    const afterDisplay=await page.evaluate(async()=>({scan:await api('scan',{id:state.scan.id}),profile:await api('profile',{id:state.scan.id,start:[.1,.1],end:[.9,.9]})}));
    assert.deepEqual(afterDisplay.scan.data,beforeDisplay.scan.data,'manual range and palette leave numerical data unchanged');
    assert.deepEqual(afterDisplay.scan.statistics,beforeDisplay.scan.statistics,'manual range leaves statistics unchanged');
    assert.deepEqual(afterDisplay.profile.values,beforeDisplay.profile.values,'manual range leaves profile values unchanged');
    assert.equal(afterDisplay.scan.display.mode,'manual');assert.equal(afterDisplay.scan.display.palette,'gray');
    assert.equal(afterDisplay.scan.display.minimum,manual[0]);assert.equal(afterDisplay.scan.display.maximum,manual[1]);
    await page.getByRole('button',{name:'Original',exact:true}).click();await idle();
    assert.deepEqual(await page.evaluate(()=>canvasRanges),manual,'manual limits are shared while comparing Original');
    await page.getByRole('button',{name:'Result',exact:true}).click();await idle();
    await page.reload();await page.waitForSelector('.scan-card');await page.evaluate(id=>openScan(id),scan.id);
    await idle();
    assert.deepEqual(await page.evaluate(()=>canvasRanges),manual,'manual color limits survive reopen');
    const provenance=await page.evaluate(async()=>JSON.parse((await api('export_scan',{id:state.scan.id})).content));
    assert(provenance.display,'provenance exports display settings');assert(provenance.mask||provenance.scan.mask,'provenance exports mask');

    console.log('Checking auto/full/ROI ranges and invalid controls');
    await showPanel('view');
    await displayAction('full');
    await page.evaluate(()=>AFMDisplay.pending());
    await page.waitForFunction(()=>state.scan.display?.mode==='full'||(canvasRanges[0]===state.scan.statistics.min&&canvasRanges[1]===state.scan.statistics.max));
    assert.deepEqual(await page.evaluate(()=>canvasRanges),[beforeDisplay.scan.statistics.min,beforeDisplay.scan.statistics.max]);
    await displayAction('auto');
    await page.evaluate(()=>AFMDisplay.pending());
    await page.waitForFunction(()=>canvasRanges[0]>state.scan.statistics.min&&canvasRanges[1]<state.scan.statistics.max);
    const autoOptions=page.locator('.color-auto-options');
    if(!await autoOptions.evaluate(el=>el.open))await autoOptions.locator('summary').click();
    await page.locator('#contrast-slider').focus();await page.keyboard.press('ArrowRight');
    await page.evaluate(()=>AFMDisplay.pending());
    assert.equal(await page.evaluate(()=>AFMDisplay.settings().clip_percent),2.5,'auto-range tuning accepts keyboard adjustment');
    assert(await autoOptions.evaluate(el=>el.open),'auto-range options remain open after applying a change');
    await selectTool('area');await draw([.05,.05],[.18,.18]);
    await page.waitForFunction(()=>!state.loading&&!!state.area);
    const roiExpected=await page.evaluate(()=>api('display_range',{id:state.scan.id,mode:'roi',roi:state.area.roi}));
    await showPanel('view');
    await displayAction('roi');
    await page.evaluate(()=>AFMDisplay.pending());
    await page.waitForFunction(range=>canvasRanges[0]===range.minimum&&canvasRanges[1]===range.maximum,roiExpected);
    const roiRange=await page.evaluate(()=>canvasRanges.slice());
    await page.locator('#color-lower-slider').focus();await page.keyboard.press('ArrowRight');await page.evaluate(()=>AFMDisplay.pending());
    await page.locator('#color-upper-slider').focus();await page.keyboard.press('ArrowLeft');await page.evaluate(()=>AFMDisplay.pending());
    const sliderRange=await page.evaluate(()=>canvasRanges.slice());
    assert(sliderRange[0]>roiRange[0]&&sliderRange[1]<roiRange[1],'keyboard-adjustable range sliders change both limits');
    const validRange=await page.evaluate(()=>canvasRanges.slice());
    await page.locator('#color-min-input').fill('10');await page.locator('#color-max-input').fill('-10');
    expectedApiFailure=true;await displayAction('manual');
    await page.waitForFunction(()=>document.querySelector('#toast')?.textContent||document.querySelector('[role="alert"]')?.textContent);
    expectedApiFailure=false;assert.deepEqual(await page.evaluate(()=>canvasRanges),validRange,'inverted manual limits cannot replace valid limits');

    await selectMask();await page.locator('#mask-use').selectOption('exclude');await idle();
    await page.locator('[data-mask-edit="add"]').click();
    const threshold=page.locator('.mask-threshold');if(!await threshold.evaluate(el=>el.open))await threshold.locator('summary').click();
    await fill('mask-lower',beforeDisplay.scan.statistics.mean);await fill('mask-upper',beforeDisplay.scan.statistics.max);
    before=await mask();await page.locator('[data-mask-action="threshold"]').click();await waitMask(before.revision);
    assert((await mask()).count>0,'full-resolution threshold adds selected values');
    assert(await threshold.evaluate(el=>el.open),'threshold options remain open after a mask edit');
    const thresholdMask=await mask();
    await maskAction('Clear mask');await page.locator('#mask-use').selectOption('include');await idle();
    assert.equal(await page.evaluate(()=>state.scan.masked_statistics),null,'empty included mask is not replaced by whole-image statistics');
    assert.match(await page.evaluate(()=>state.scan.masked_statistics_error),/no valid/i);
    await maskAction('Undo mask');assert.equal((await mask()).data_base64,thresholdMask.data_base64);
    await page.locator('#mask-use').selectOption('ignore');await idle();
    assert.equal(await page.evaluate(()=>AFMMask.active()),false,'ignore mode disables mask application');
    assert.equal(await page.evaluate(()=>state.scan.statistics.count),scan.width*scan.height,'ignore mode displays whole-image statistics');
    await page.locator('#mask-use').selectOption('exclude');await idle();
    const dir=path.resolve('.test-artifacts');fs.mkdirSync(dir,{recursive:true});
    await page.getByRole('button',{name:'Export',exact:true}).click();
    const downloaded=page.waitForEvent('download');
    await page.locator('[data-action="export-format"][data-format="png"]').click();
    const pngPath=path.join(dir,'masking-display-export.png');await (await downloaded).saveAs(pngPath);
    const png=fs.readFileSync(pngPath);
    assert.equal(png.subarray(1,4).toString(),'PNG');assert.equal(png.readUInt32BE(16),1100);assert.equal(png.readUInt32BE(20),1240);
    await page.waitForFunction(()=>!document.querySelector('#toast').classList.contains('show'));
    await page.screenshot({path:path.join(dir,'masking-display.png')});
    await selectTool('inspect');await showPanel('view');
    await page.screenshot({path:path.join(dir,'color-range-controls.png')});
    await selectMask();
    await page.setViewportSize({width:900,height:650});
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    await page.waitForTimeout(200);
    const compactDOM=await page.evaluate(()=>({shells:document.querySelectorAll('.app-shell').length,sidebars:document.querySelectorAll('.sidebar').length,headers:document.querySelectorAll('.topbar').length,details:document.querySelectorAll('.detail-view').length,bodyHeight:document.body.scrollHeight,viewportHeight:innerHeight}));
    assert.deepEqual([compactDOM.shells,compactDOM.sidebars,compactDOM.headers,compactDOM.details],[1,1,1,1],'compact view has one application tree');
    console.log('Compact DOM:',JSON.stringify(compactDOM));
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'compact viewport does not overflow horizontally');
    const image=await page.locator('#height-canvas').boundingBox();assert(image&&image.width>0&&image.height>0,'image remains visible');
    await page.screenshot({path:path.join(dir,'masking-display-compact.png')});
    const sparseOverlay=await page.evaluate(()=>{
      const saved=state.scan,bytes=new Uint8Array(1024*1024/8);bytes[0]=128;
      let binary='';for(const byte of bytes)binary+=String.fromCharCode(byte);
      try{
        state.scan={...saved,id:'synthetic-overlay-regression',width:1024,height:1024,data_width:512,data_height:512,mask:{...saved.mask,width:1024,height:1024,count:1,revision:1,visible:true,data_base64:btoa(binary)}};
        AFMMask.paint();const canvas=document.getElementById('mask-canvas');
        return Array.from(canvas.getContext('2d').getImageData(0,0,2,1).data);
      }finally{state.scan=saved;AFMMask.paint();}
    });
    assert(sparseOverlay[3]>0&&sparseOverlay[7]===0,'a lone source pixel remains visible in a reduced overlay without marking its neighbor');
    console.log('Checking per-image comparison limits, palettes and selected statistics');
    const second=session.scans.find(item=>item.channel==='Z Height'&&item.id!==scan.id);
    await page.setViewportSize({width:1280,height:900});
    const compare=await page.evaluate(async ids=>{
      await api('set_display',{id:ids[1],settings:{palette:'amber',mode:'manual',minimum:-2,maximum:20,clip_percent:0}});
      state.selected=new Set(ids);await actions.compare();
      return state.comparison.map(s=>({id:s.id,range:s.comparison_range,display:s.display,stats:s.statistics,masked:s.masked_statistics}));
    },[scan.id,second.id]);
    await idle();
    assert.deepEqual(compare[0].range,validRange,'comparison retains the first image manual limits');
    assert.deepEqual(compare[1].range,[-2,20],'comparison retains the second image manual limits');
    assert.equal(compare[0].display.palette,'gray');assert.equal(compare[1].display.palette,'amber');
    assert(await page.getByText('Mask applied to statistics',{exact:false}).count()>0,'comparison discloses masked statistics');
    const independentPixels=await page.locator('[data-compare-canvas]').evaluateAll(canvases=>canvases.map(canvas=>Array.from(canvas.getContext('2d').getImageData(0,0,1,1).data)));
    assert(Math.max(...independentPixels[0].slice(0,3))-Math.min(...independentPixels[0].slice(0,3))<=6,'first comparison uses its neutral gray palette');
    assert(Math.max(...independentPixels[1].slice(0,3))-Math.min(...independentPixels[1].slice(0,3))>6,'second comparison uses its amber palette');
    await page.getByRole('button',{name:'Independent display ranges',exact:true}).click();await idle();
    assert.equal(await page.evaluate(()=>state.commonRange),true);
    const sharedPixels=await page.locator('[data-compare-canvas]').evaluateAll(canvases=>canvases.map(canvas=>Array.from(canvas.getContext('2d').getImageData(0,0,1,1).data)));
    assert(sharedPixels.every(pixel=>Math.max(...pixel.slice(0,3))-Math.min(...pixel.slice(0,3))<=6),'shared comparison uses one neutral gray palette');
    assert.deepEqual(await page.evaluate(()=>state.comparison.map(s=>s.statistics)),compare.map(s=>s.stats),'shared contrast leaves comparison statistics unchanged');
    await page.screenshot({path:path.join(dir,'masking-display-compare.png')});
    assert.deepEqual(errors,[],'no unexpected browser errors');
    console.log('PASS: mask rectangle/brush/erase/invert/threshold/undo/redo, empty selection, include/exclude/ignore analysis, recipe snapshots, persistence, immutable originals, numeric/sliders/auto/full/ROI color ranges, display invariance, provenance, PNG export, per-image/shared comparison, compact layout.');
  }finally{if(browser)await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
